#include <stdio.h>

int main()
{
    int n, s, k;

    // লাইন সংখ্যা ইনপুট নেওয়া
    scanf("%d", &n);

    s = n - 1; // প্রথম লাইনে কতগুলো স্পেস থাকবে
    k = 1;     // প্রথম লাইনে কতগুলো স্টার থাকবে

    for (int i = 1; i <= n; i++)
    {
        // ১. স্পেস প্রিন্ট করার লুপ
        for (int j = 1; j <= s; j++)
        {
            printf(" ");
        }

        // ২. স্টার প্রিন্ট করার লুপ
        for (int j = 1; j <= k; j++)
        {
            printf("*");
        }

        // ৩. এক লাইনের কাজ শেষে পরবর্তী লাইনের প্রস্তুতি
        s--;          // স্পেস ১টি কমবে
        k = k + 2;    // স্টার ২টো বাড়বে
        printf("\n"); // কার্সার পরের লাইনে নিয়ে যাওয়া
    }

    return 0;
}