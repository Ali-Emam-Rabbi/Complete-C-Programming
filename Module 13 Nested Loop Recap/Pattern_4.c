#include <stdio.h>

int main()
{
    int n, s, k;

    // লাইন সংখ্যা ইনপুট নেওয়া
    scanf("%d", &n);

    s = n - 1; // প্রথম লাইনে কতগুলো স্পেস থাকবে
    k = 1;     // প্রথম লাইনে কতগুলো স্টার থাকবে

    // মোট (2*n - 1) টি লাইনের জন্য লুপ
    for (int i = 1; i <= (2 * n) - 1; i++)
    {
        // ১. স্পেস প্রিন্ট করার লুপ
        for (int j = 1; j <= s; j++)
        {
            printf(" ");
        }

        // ২. স্টার প্রিন্ট করার লুপ
        for (int j = 1; j <= k; j++)
        {
            printf("*");
        }

        // ৩. এক লাইনের কাজ শেষ, পরের লাইনের জন্য সিদ্ধান্ত
        if (i <= n - 1)
        {
            // ডায়মন্ডের উপরের অংশ: স্পেস কমবে, স্টার বাড়বে
            s--;
            k = k + 2;
        }
        else
        {
            // ডায়মন্ডের নিচের অংশ: স্পেস বাড়বে, স্টার কমবে
            s++;
            k = k - 2;
        }

        printf("\n"); // পরের লাইনে যাওয়া
    }

    return 0;
}