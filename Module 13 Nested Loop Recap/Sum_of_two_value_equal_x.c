#include <stdio.h> // Standard I/O

int main()
{
    int n;
    scanf("%d", &n); // ১. অ্যারের সাইজ (N) ইনপুট নেওয়া

    int a[n];
    for (int i = 0; i < n; i++)
    {
        scanf("%d", &a[i]); // ২. অ্যারের উপাদানগুলো ইনপুট নেওয়া
    }

    int x;
    scanf("%d", &x); // ৩. টার্গেট মান X ইনপুট নেওয়া

    int flag = 0; // জোড়া পাওয়া গেছে কি না তা ট্র্যাক করার জন্য (০ = পাওয়া যায়নি, ১ = পাওয়া গেছে)

    // ৪. দুটি লুপ দিয়ে সব সম্ভাব্য জোড়া (Pairs) চেক করা
    for (int i = 0; i < n - 1; i++)
    {
        for (int j = i + 1; j < n; j++)
        {
            if (a[i] + a[j] == x)
            {
                flag = 1; // জোড়া পাওয়া গেলে flag ১ করে দেওয়া
            }
        }
    }

    // ৫. ফলাফল প্রিন্ট করা
    if (flag == 1)
    {
        printf("YES\n");
    }
    else
    {
        printf("NO\n");
    }

    return 0;
}

// আপনাকে একটি সংখ্যা $N$, একটি $N$ আকারের অ্যারে (Array),
// এবং একটি টার্গেট সংখ্যা $X$ দেওয়া হবে। আপনাকে খুঁজে বের করতে হবে—
// অ্যারের যেকোনো দুটি আলাদা উপাদানের যোগফল $X$-এর সমান হয় কি না।
// যদি এমন কোনো জোড়া (pair) পাওয়া যায়, তবে "YES" প্রিন্ট করবে।
// যদি পুরো অ্যারে খুঁজেও এমন কোনো জোড়া না পাওয়া যায়, তবে "NO" প্রিন্ট করবে।