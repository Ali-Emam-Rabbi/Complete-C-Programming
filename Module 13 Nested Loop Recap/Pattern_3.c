#include <stdio.h>

int main()
{
    int n, k = 1;

    // ইনপুট নেওয়া (কয়টা লাইন হবে)
    scanf("%d", &n);

    for (int i = 1; i <= n; i++)
    {
        // প্রতিটি লাইনে 1 থেকে k পর্যন্ত সংখ্যা প্রিন্ট করার লুপ
        for (int j = 1; j <= k; j++)
        {
            printf("%d ", j);
        }

        k++;          // পরের লাইনে ১টি সংখ্যা বেশি প্রিন্ট করার জন্য k এর মান বাড়ান
        printf("\n"); // নিউ লাইন বা পরের লাইনে যাওয়া
    }

    return 0;
}