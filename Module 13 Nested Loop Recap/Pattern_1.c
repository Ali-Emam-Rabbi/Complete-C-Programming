#include <stdio.h>

int main()
{
    int n, k = 1;

    // লাইন সংখ্যা ইনপুট নেওয়া
    scanf("%d", &n);

    for (int i = 1; i <= n; i++)
    {
        // প্রতিটি লাইনে k সংখ্যক স্টার প্রিন্ট করার লুপ
        for (int j = 1; j <= k; j++)
        {
            printf("*");
        }

        k++;          // পরের লাইনের জন্য স্টারের সংখ্যা ১ বাড়ানো
        printf("\n"); // কার্সার পরের লাইনে নেওয়া
    }

    return 0;
}