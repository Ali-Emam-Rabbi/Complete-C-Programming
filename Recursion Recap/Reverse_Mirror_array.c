#include <stdio.h>
int main()
{
    int row, col;
    printf("Enter Numbers Of Row: ");
    scanf("%d", &row);

    printf("Enter Numbers Of Columns: ");
    scanf("%d", &col);

    int a[row][col];

    printf("Enter Matrix Numbers:\n");
    for (int i = 0; i < row; i++)
    {
        for (int j = 0; j < col; j++)
        {
            scanf("%d", &a[i][j]);
        }
    }

    printf("Revers Mirror Matrix:\n");
    for (int i = 0; i < row; i++)
    {
        for (int j = col - 1; j >= 0; j--)
        {
            printf("%d ", a[i][j]);
        }
        printf("\n");
    }

    return 0;
}

// for(int j = col - 1; j >= 0; j--) উদাহরণসহ বিস্তারিত ব্যাখ্যা

// ধরি, আমাদের কলাম সংখ্যা col = 3 এবং কোনো একটি রো-এর ভেতরের ৩টি
// উপাদান হলো [10, 20, 30]।

// এরে-তে ইনডেক্স শুরু হয় 0 থেকে:

// a[i][0] = 10

// a[i][1] = 20

// a[i][2] = 30

// সাধারণভাবে প্রিন্ট করলে লুপ চলে 0 থেকে 2 পর্যন্ত, যা প্রিন্ট করে 10 20 30। কিন্তু উল্টো প্রিন্ট করতে আমাদের লাগবে 30 20 10, অর্থাৎ ইনডেক্স ঘুরবে 2 -> 1 -> 0।

// লুপটি যেভাবে ধাপে ধাপে কাজ করে:

// শুরু (int j = col - 1):
// এখানে j = 3 - 1 = 2। লুপটি শুরুই হবে কলামের শেষ ইনডেক্স 2 থেকে।

// প্রিন্ট হবে: a[i][2] অর্থাৎ 30।

// শর্ত ও আপডেট (j >= 0; j--):
// প্রতিবার প্রিন্ট শেষে j-- এর মাধ্যমে ইনডেক্স ১ করে কমবে, যতক্ষণ না 0 এর চেয়ে ছোট হয় (j >= 0)।

// j = 1: শর্ত সত্য (1 >= 0) -> প্রিন্ট হবে: a[i][1] অর্থাৎ 20।

// j = 0: শর্ত সত্য (0 >= 0) -> প্রিন্ট হবে: a[i][0] অর্থাৎ 10।

// j = -1: শর্ত মিথ্যা (-1 >= 0) -> লুপ বন্ধ হয়ে যাবে।

// আউটপুট: 30 20 10 (রো-এর মানগুলো রিভার্স হয়ে গেল)।